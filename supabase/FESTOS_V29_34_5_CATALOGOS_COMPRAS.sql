-- FESTOS V29.34.5 - Catálogos Registro de Compras
alter table public.compras
  add column if not exists lob text,
  add column if not exists ceco text,
  add column if not exists categoria_gasto text;

create table if not exists public.compras_lob_catalogo (
  id bigint generated by default as identity primary key,
  nombre text not null unique,
  activo boolean not null default true,
  orden integer not null default 0,
  created_at timestamptz not null default now()
);
insert into public.compras_lob_catalogo (nombre, orden) values
  ('ESPACIOS Y ESTRUCTURAS',1),('GRAFICA PUBLICITARIA',2),('MERCH & GIFTS',3),('AGENCIA 360°',4),('FESTOS',5)
on conflict (nombre) do update set activo=true, orden=excluded.orden;

create table if not exists public.compras_ceco_catalogo (
  id bigint generated by default as identity primary key,
  nombre text not null unique,
  activo boolean not null default true,
  orden integer not null default 0,
  created_at timestamptz not null default now()
);
insert into public.compras_ceco_catalogo (nombre, orden) values
  ('ADMINISTRACIÓN',1),('COMERCIAL',2),('OPERACIONES',3),('INTERNO',4)
on conflict (nombre) do update set activo=true, orden=excluded.orden;

create table if not exists public.compras_categoria_gasto_catalogo (
  id bigint generated by default as identity primary key,
  nombre text not null unique,
  activo boolean not null default true,
  orden integer not null default 0,
  created_at timestamptz not null default now()
);
insert into public.compras_categoria_gasto_catalogo (nombre, orden) values
  ('Abastecimiento Stock',1),('Alquileres',2),('Costos Directos',3),('Gastos administrativos',4),
  ('Gastos de Representación / Eventos',5),('Infraestructura y equipos',6),('Mantenimiento / Víveres / Insumos',7),
  ('MKT y Publicidad',8),('Movilidad - Combustible',9),('Otros costos variables',10),('Remuneraciones',11),
  ('Seguros',12),('Servicios de terceros',13),('Utilities',14)
on conflict (nombre) do update set activo=true, orden=excluded.orden;

alter table public.compras_lob_catalogo enable row level security;
alter table public.compras_ceco_catalogo enable row level security;
alter table public.compras_categoria_gasto_catalogo enable row level security;

drop policy if exists "lob_catalogo_select" on public.compras_lob_catalogo;
create policy "lob_catalogo_select" on public.compras_lob_catalogo for select to authenticated using (activo=true);
drop policy if exists "ceco_catalogo_select" on public.compras_ceco_catalogo;
create policy "ceco_catalogo_select" on public.compras_ceco_catalogo for select to authenticated using (activo=true);
drop policy if exists "categoria_gasto_catalogo_select" on public.compras_categoria_gasto_catalogo;
create policy "categoria_gasto_catalogo_select" on public.compras_categoria_gasto_catalogo for select to authenticated using (activo=true);

create index if not exists compras_lob_idx on public.compras(lob);
create index if not exists compras_ceco_idx on public.compras(ceco);
create index if not exists compras_categoria_gasto_idx on public.compras(categoria_gasto);
